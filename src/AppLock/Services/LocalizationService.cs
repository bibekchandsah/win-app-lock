using System.Globalization;

namespace AppLock.Services;

public class LocalizationService
{
    private string _currentLanguage = "System default";
    private string _effectiveLanguageCode = "en";

    public event EventHandler? LanguageChanged;

    public string CurrentLanguage => _currentLanguage;
    public string EffectiveLanguageCode => _effectiveLanguageCode;

    public LocalizationService(string initialLanguage = "System default")
    {
        SetLanguage(initialLanguage);
    }

    public void SetLanguage(string language)
    {
        _currentLanguage = string.IsNullOrWhiteSpace(language) ? "System default" : language;
        _effectiveLanguageCode = ResolveLanguageCode(_currentLanguage);
        LanguageChanged?.Invoke(this, EventArgs.Empty);
    }

    private static string ResolveLanguageCode(string language)
    {
        return language switch
        {
            "English" => "en",
            "Spanish" => "es",
            "French" => "fr",
            "German" => "de",
            "Italian" => "it",
            "Portuguese" => "pt",
            "Chinese" => "zh",
            "Japanese" => "ja",
            "Nepali" => "ne",
            "Hindi" => "hi",
            "System default" or _ => GetSystemDefaultCode()
        };
    }

    private static string GetSystemDefaultCode()
    {
        var twoLetter = CultureInfo.CurrentUICulture.TwoLetterISOLanguageName.ToLowerInvariant();
        return twoLetter switch
        {
            "es" => "es",
            "fr" => "fr",
            "de" => "de",
            "it" => "it",
            "pt" => "pt",
            "zh" => "zh",
            "ja" => "ja",
            "ne" => "ne",
            "hi" => "hi",
            _ => "en"
        };
    }

    public string GetString(string key)
    {
        if (Translations.TryGetValue(_effectiveLanguageCode, out var dict) && dict.TryGetValue(key, out var val))
        {
            return val;
        }

        // Fallback to English
        if (Translations.TryGetValue("en", out var enDict) && enDict.TryGetValue(key, out var enVal))
        {
            return enVal;
        }

        return key;
    }

    public string this[string key] => GetString(key);

